/** Legacy room-title check: no swearing (also with digits or spaces between the letters)... */
export function isBad(text) {
	return text.search(BAD) !== -1 || text.replace(/[\d\s]/g, '').search(BAD) !== -1;
}

/** ...and only letters, digits and a few marks. */
export const isAllowedText = (text) => /^[A-Za-z0-9가-힣ㄱ-ㅎㅏ-ㅣ._@!\-()[\]*? ]+$/.test(text);

/** Replaces each match with hearts of the same length, like the legacy 필터 켜기. */
export const maskBad = (text) => text.replace(BAD, (m) => '♥'.repeat(m.length));

/**
 * Catches a word typed over several short messages ("씨" then "발"). One buffer per sender, kept for 10 s.
 * Returns the text to show (hearts when a split word completed).
 */
export function createSplitFilter() {
	const buffers = {};
	return function filterSplit(senderId, raw, now = Date.now()) {
		if (!senderId) return raw;
		let buf = buffers[senderId];
		if (!buf || now - buf.t > 10_000) buf = buffers[senderId] = { s: '', t: now };
		let norm = raw.replace(/[\s0-9!@#$%^&*()_+={}\[\]:;"'<>,.?/\\|`~-]/g, '');
		if (norm === '') norm = raw.trim();
		if (norm.length > 3 || norm.search(BAD) !== -1) {
			buf.s = '';
			buf.t = now;
			return raw;
		}
		const prev = buf.s;
		buf.s = (prev + norm).slice(-10);
		buf.t = now;
		if (prev && buf.s.search(BAD) !== -1) {
			buf.s = '';
			return raw.replace(/[^\s]/g, '♥');
		}
		return raw;
	};
}
